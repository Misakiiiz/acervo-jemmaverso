create table if not exists public.site_admins (
  user_id uuid primary key references auth.users (id) on delete cascade
);
alter table public.site_admins enable row level security;      -- sem policies: só o SQL Editor mexe aqui
revoke all on public.site_admins from anon, authenticated;

create or replace function public.is_site_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.site_admins where user_id = auth.uid())
$$;
revoke all on function public.is_site_admin() from public;
grant execute on function public.is_site_admin() to anon, authenticated;

-- AUs adicionadas pelo painel (ids começam em 1000 para nunca bater com o data.js)
create table if not exists public.admin_aus (
  id           integer generated by default as identity (start with 1000) primary key,
  title        text not null check (char_length(title) between 1 and 160),
  authors      text not null check (char_length(authors) between 1 and 200),  -- handles sem @, ex.: "agloveswencl4ir e Lollipop_Raven"
  fandom       text not null check (char_length(fandom) between 1 and 60),
  status       text not null default 'Não informado',
  size         text not null default 'Short',
  description  text not null default '' check (char_length(description) <= 2000),
  tags         text[] not null default '{}',
  url          text not null check (url ~ '^https?://'),
  read_url     text check (read_url is null or read_url ~ '^https?://'),
  series       text,
  series_order integer,
  created_at   timestamptz not null default now()
);
alter table public.admin_aus enable row level security;

drop policy if exists "aus: todos leem" on public.admin_aus;
create policy "aus: todos leem" on public.admin_aus for select to anon, authenticated using (true);
drop policy if exists "aus: admin insere" on public.admin_aus;
create policy "aus: admin insere" on public.admin_aus for insert to authenticated with check (public.is_site_admin());
drop policy if exists "aus: admin edita" on public.admin_aus;
create policy "aus: admin edita" on public.admin_aus for update to authenticated using (public.is_site_admin()) with check (public.is_site_admin());
drop policy if exists "aus: admin apaga" on public.admin_aus;
create policy "aus: admin apaga" on public.admin_aus for delete to authenticated using (public.is_site_admin());
grant select on public.admin_aus to anon, authenticated;
grant insert, update, delete on public.admin_aus to authenticated;

